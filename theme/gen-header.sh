#!/usr/bin/env bash
# Renders the black palette into launcher/src/theme-black.h: the launcher's own
# stylesheet (its fallback when ~/.config/tux-mc/style.css is missing) and
# Prism's "tux" theme, which the setup screen installs. Run it after changing
# the templates; the header is committed, so building needs no envsubst.
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd)
OUT=$D/../launcher/src/theme-black.h

before=$(compgen -v | sort)
# shellcheck source=/dev/null
source "$D/palettes/black.sh"
vars=()
for v in $(comm -13 <(echo "$before") <(compgen -v | sort) | grep -E '^[a-z][a-z0-9_]*$'); do
    export "${v?}"
    vars+=("$v")
done
fmt=$(printf '${%s} ' "${vars[@]}")

# a file as one C string literal, line by line
lit() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/'; }
cstr() { envsubst "$fmt" < "$1" | lit; }

{
    echo "/* theme-black.h: generated by theme/gen-header.sh from the templates in theme/"
    echo " * and theme/palettes/black.sh. Don't edit; run the script. */"
    echo "#pragma once"
    echo
    echo "static const char TUX_STYLE_CSS[] ="
    cstr "$D/tux-mc.css"
    echo "    ;"
    echo
    echo "static const char PRISM_THEME_JSON[] ="
    cstr "$D/prism-theme.json"
    echo "    ;"
    echo
    echo "static const char PRISM_THEME_CSS[] ="
    cstr "$D/prism-theme.css"
    echo "    ;"
    echo
    echo "/* the same templates with \${name} left in, for theme presets (mc-themes.c) */"
    echo "static const char TUX_STYLE_TEMPLATE[] ="
    lit < "$D/tux-mc.css"
    echo "    ;"
    echo
    echo "static const char PRISM_THEME_JSON_TEMPLATE[] ="
    lit < "$D/prism-theme.json"
    echo "    ;"
    echo
    echo "static const char PRISM_THEME_CSS_TEMPLATE[] ="
    lit < "$D/prism-theme.css"
    echo "    ;"
} > "$OUT"
echo "wrote $OUT"
